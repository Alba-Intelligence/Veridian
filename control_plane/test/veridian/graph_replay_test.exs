defmodule Veridian.GraphReplayTest do
  @moduledoc """
  Replays Quint traces of `models/calc_graph.qnt` (instance `calc_graph_fixed`)
  against `Veridian.Graph` (policy section 7, D-059). After every step the
  model's state must equal the projection of the real state; a difference is a
  finding, not a test to adjust.

  Two kinds of trace are committed:

    * `fixtures/traces/calc_graph/` - random runs written with `--mbt`, so each
      step names its action and arguments (deterministic replay).
    * `fixtures/traces/calc_graph_scenarios/` - the model's scenarios from
      `quint test`, which reach what random runs cannot (fulfilment, early
      cutoff, lost recomputations). They carry no action names, so each step is
      inferred: some action of the code must reproduce the model's next state.

  Both are regenerated by `veridian-traces` and committed only when the model
  changes. The same traces are replayed against the Postgres ledger in
  `Veridian.LedgerReplayTest`.
  """
  use ExUnit.Case, async: true

  alias Veridian.Test.{CalcGraphAdapter, Replay, Traces}

  test "trace fixtures exist" do
    assert length(Traces.random()) >= 10, "run veridian-traces"
    assert length(Traces.scenarios()) == 7, "run veridian-traces"
  end

  test "traces were written from the current model files" do
    assert Traces.current_models_hash() == Traces.recorded_models_hash(),
           "models/calc_graph*.qnt changed since the traces were written; run veridian-traces"
  end

  for trace <- Traces.random() do
    @trace trace
    test "random trace #{Path.basename(trace)}" do
      Replay.named(CalcGraphAdapter, @trace)
    end
  end

  for trace <- Traces.scenarios() do
    @trace trace
    test "scenario #{Path.basename(trace)}" do
      assert Replay.inferred(CalcGraphAdapter, @trace) != []
    end
  end

  test "the committed traces reach every action of the model" do
    named = Enum.flat_map(Traces.random(), &Replay.named(CalcGraphAdapter, &1))
    inferred = Enum.flat_map(Traces.scenarios(), &Replay.inferred(CalcGraphAdapter, &1))
    missing = Traces.all_actions() -- Enum.uniq(named ++ inferred)
    assert missing == [], "actions never replayed: #{inspect(missing)}"
  end
end
